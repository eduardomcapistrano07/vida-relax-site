window.filterTab = function filterTab(btn, cat) {
  const inner = btn.closest(".products-inner");
  if (!inner) return;
  const slug =
    typeof cat === "string" ? cat : (btn.dataset.filter || "todos");
  const grid = inner.querySelector(".products-grid");
  const catalogWrap = btn.closest("#page-catalogo");

  if (catalogWrap && grid && grid.id === "catalog-grid") {
    inner.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    applyCatalogFilters();
    return;
  }

  if (grid && grid.id === "home-featured-grid") {
    if (btn.classList.contains("active")) {
      inner.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("active"));
      applyHomeFeaturedFilter("principal");
      return;
    }
    inner.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("active"));
    btn.classList.add("active");
    applyHomeFeaturedFilter(slug);
    return;
  }

  inner.querySelectorAll(".tab-btn").forEach((b) => b.classList.remove("active"));
  btn.classList.add("active");

  if (!grid) return;
  grid.querySelectorAll(".product-card[data-category]").forEach((card) => {
    const c = card.dataset.category;
    const show = categoryMatchesFilter(c, slug);
    card.style.display = show ? "" : "none";
  });
};

function goCatalogSlide(carouselRoot, delta) {
  const slides = carouselRoot.querySelectorAll(".catalog-carousel-slide");
  const dots = carouselRoot.querySelectorAll(".catalog-carousel-dot");
  if (!slides.length) return;

  carouselSlideIndex =
    (carouselSlideIndex + delta + slides.length) % slides.length;
  slides.forEach((s, i) => {
    s.classList.toggle("is-active", i === carouselSlideIndex);
  });
  dots.forEach((d, i) => {
    d.classList.toggle("is-active", i === carouselSlideIndex);
    d.setAttribute("aria-selected", i === carouselSlideIndex ? "true" : "false");
  });
}

function initCatalogCarousel() {
  const root = document.getElementById("catalog-carousel");
  if (!root || root.dataset.inited === "1") return;
  root.dataset.inited = "1";

  root.addEventListener("mouseenter", () => {
    carouselPaused = true;
  });
  root.addEventListener("mouseleave", () => {
    carouselPaused = false;
  });

  root.querySelectorAll(".catalog-carousel-dot").forEach((dot, idx) => {
    dot.addEventListener("click", () => {
      const slides = root.querySelectorAll(".catalog-carousel-slide");
      carouselSlideIndex = idx;
      slides.forEach((s, i) => {
        s.classList.toggle("is-active", i === carouselSlideIndex);
      });
      root.querySelectorAll(".catalog-carousel-dot").forEach((d, i) => {
        d.classList.toggle("is-active", i === carouselSlideIndex);
        d.setAttribute(
          "aria-selected",
          i === carouselSlideIndex ? "true" : "false",
        );
      });
    });
  });

  clearInterval(catalogCarouselTimer);
  catalogCarouselTimer = null;
  const slideN = root.querySelectorAll(".catalog-carousel-slide").length;
  if (slideN > 1) {
    catalogCarouselTimer = setInterval(() => {
      if (carouselPaused) return;
      goCatalogSlide(root, 1);
    }, CATALOG_CAROUSEL_AUTO_MS);
  }
}

