function avgStars(reviews) {
  if (!reviews || !reviews.length) return 0;
  const s = reviews.reduce((a, r) => a + r.stars, 0);
  return s / reviews.length;
}

function getProductGallery(p) {
  const base = [p.img, p.imgHover];
  const extras = PRODUCT_GALLERY_EXTRA[p.id] || [];
  return [...new Set([...base, ...extras].filter(Boolean))];
}

/** Itens da galeria PDP: vídeo opcional (após a 1ª imagem) + demais imagens. */
function getProductMediaItems(p) {
  const images = getProductGallery(p);
  const items = images.map((src) => ({ type: "image", src }));
  if (p.galleryVideo && String(p.galleryVideo).trim()) {
    const vid = { type: "video", src: String(p.galleryVideo).trim() };
    if (items.length) items.splice(1, 0, vid);
    else items.push(vid);
  }
  return items;
}

/** Cinco estrelas ★ com meia-estrela (0,5). Sem avaliações, todas vazias. */
function renderRatingStarSpans(avg, hasReviews) {
  if (!hasReviews) {
    return [1, 2, 3, 4, 5]
      .map(
        () => `<span class="star empty" aria-hidden="true">★</span>`,
      )
      .join("");
  }
  const a = Math.max(0, Math.min(5, Number(avg) || 0));
  return [1, 2, 3, 4, 5]
    .map((i) => {
      if (a >= i) return `<span class="star" aria-hidden="true">★</span>`;
      if (a >= i - 0.5)
        return `<span class="star half" aria-hidden="true">★</span>`;
      return `<span class="star empty" aria-hidden="true">★</span>`;
    })
    .join("");
}

