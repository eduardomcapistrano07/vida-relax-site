function initMobileNav() {
  const toggle = document.getElementById("nav-menu-toggle");
  const nav = document.getElementById("primary-navigation");
  const backdrop = document.getElementById("nav-drawer-backdrop");
  if (!toggle || !nav) return;

  const mqDrawer = window.matchMedia("(max-width: 900px)");
  let lastFocus = null;

  function syncNavAccessibility(open) {
    if (!mqDrawer.matches) {
      nav.removeAttribute("aria-hidden");
      nav.classList.remove("is-open");
      if ("inert" in HTMLElement.prototype) nav.inert = false;
      toggle.setAttribute("aria-expanded", "false");
      toggle.setAttribute("aria-label", "Abrir menu");
      document.body.classList.remove("nav-drawer-open");
      if (backdrop) backdrop.setAttribute("hidden", "");
      return;
    }
    nav.setAttribute("aria-hidden", open ? "false" : "true");
    if ("inert" in HTMLElement.prototype) {
      nav.inert = !open;
    }
  }

  function setOpen(open) {
    if (!mqDrawer.matches) return;
    toggle.setAttribute("aria-expanded", open ? "true" : "false");
    toggle.setAttribute("aria-label", open ? "Fechar menu" : "Abrir menu");
    nav.classList.toggle("is-open", open);
    document.body.classList.toggle("nav-drawer-open", open);
    if (backdrop) {
      if (open) backdrop.removeAttribute("hidden");
      else backdrop.setAttribute("hidden", "");
      backdrop.setAttribute("aria-hidden", open ? "false" : "true");
    }
    syncNavAccessibility(open);
    if (open) {
      lastFocus = document.activeElement;
      window.requestAnimationFrame(() => {
        nav.querySelector("a")?.focus();
      });
    } else if (lastFocus && typeof lastFocus.focus === "function") {
      lastFocus.focus();
      lastFocus = null;
    }
  }

  toggle.addEventListener("click", () => {
    if (!mqDrawer.matches) return;
    setOpen(!nav.classList.contains("is-open"));
  });

  backdrop?.addEventListener("click", () => setOpen(false));

  nav.querySelectorAll("a").forEach((a) => {
    a.addEventListener("click", () => {
      if (mqDrawer.matches) setOpen(false);
    });
  });

  document.addEventListener("keydown", (e) => {
    if (e.key !== "Escape") return;
    if (!mqDrawer.matches || !nav.classList.contains("is-open")) return;
    e.preventDefault();
    setOpen(false);
  });

  window.addEventListener("resize", () => {
    if (!mqDrawer.matches) {
      nav.classList.remove("is-open");
      document.body.classList.remove("nav-drawer-open");
      backdrop?.setAttribute("hidden", "");
      toggle.setAttribute("aria-expanded", "false");
      toggle.setAttribute("aria-label", "Abrir menu");
      syncNavAccessibility(false);
    }
  });

  mqDrawer.addEventListener("change", (e) => {
    if (!e.matches) {
      nav.classList.remove("is-open");
      document.body.classList.remove("nav-drawer-open");
      backdrop?.setAttribute("hidden", "");
      toggle.setAttribute("aria-expanded", "false");
      toggle.setAttribute("aria-label", "Abrir menu");
    }
    syncNavAccessibility(nav.classList.contains("is-open"));
  });

  syncNavAccessibility(false);
}

