function bindCatalogHover(grid) {
  grid.querySelectorAll("img[data-hover-src]").forEach((img) => {
    const def = img.getAttribute("src");
    const hov = img.getAttribute("data-hover-src");
    img.addEventListener("mouseenter", () => {
      img.setAttribute("src", hov);
    });
    img.addEventListener("mouseleave", () => {
      img.setAttribute("src", def);
    });
  });
}

